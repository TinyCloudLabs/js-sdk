import { createHash } from "node:crypto";
import type { DiagnosticStore } from "./storage.js";
import { resolveDiagnosticEvidence, writeDiagnosticBundle } from "./bundles.js";
import { DiagnosticInputError, fail, keys, object, readDiagnosticJsonFile, uuid } from "./selection.js";

export interface DiagnosticFixture {
  schema_version: 1;
  kind: "wrong_units";
  fixture_id: string;
  reviewed: true;
  synthetic: true;
  expected: { value: number; unit: "U1" };
  observed: { value: number; unit: "U2" };
}
export function validateDiagnosticFixture(value: unknown): DiagnosticFixture {
  const input = object(value);
  keys(input, ["schema_version", "kind", "fixture_id", "reviewed", "synthetic", "expected", "observed"]);
  if (input.schema_version !== 1 || input.kind !== "wrong_units" || input.reviewed !== true || input.synthetic !== true) return fail();
  const expected = object(input.expected), observed = object(input.observed);
  keys(expected, ["value", "unit"]); keys(observed, ["value", "unit"]);
  if (expected.unit !== "U1" || observed.unit !== "U2" || typeof expected.value !== "number" || typeof observed.value !== "number" || !Number.isFinite(expected.value) || !Number.isFinite(observed.value) || Math.abs(expected.value) > 1000000 || Math.abs(observed.value) > 1000000) return fail();
  return { schema_version: 1, kind: "wrong_units", fixture_id: uuid(input.fixture_id), reviewed: true, synthetic: true, expected: { value: expected.value, unit: "U1" }, observed: { value: observed.value, unit: "U2" } };
}
export function diagnosticFixtureRevision(fixture: DiagnosticFixture): string {
  return createHash("sha256").update(JSON.stringify(validateDiagnosticFixture(fixture))).digest("hex");
}
