export async function bundleDiagnosticCase(store: DiagnosticStore, options: { case_id: string; fixture: string; out: string; expires_at: string; external?: boolean }) {
  const caseId = uuid(options.case_id);
  const evidence = await resolveDiagnosticEvidence(store, { case_ids: [caseId], include_detail: true });
  const selected = evidence.cases[0];
  const fixture = validateDiagnosticFixture(await readDiagnosticJsonFile(options.fixture, 4096));
  if (!selected || selected.purpose !== "synthetic_reproduction" || selected.feedback?.classification !== "wrong_units" || selected.equivalence?.fixture_id !== fixture.fixture_id || selected.equivalence.fixture_revision !== diagnosticFixtureRevision(fixture)) throw new DiagnosticInputError("missing_evidence");
  const intent = selected.passages.find((item) => item.kind === "intent" && item.unit?.value === fixture.expected.unit && selected.feedback!.passage_ids.includes(item.id));
  const observed = selected.passages.find((item) => (item.kind === "record_excerpt" || item.kind === "final_claim") && item.unit?.value === fixture.observed.unit && selected.feedback!.passage_ids.includes(item.id));
  if (!intent || !observed || [...intent.event_ids, ...observed.event_ids].some((id) => !evidence.snapshot.events.some((event) => event.event_id === id))) throw new DiagnosticInputError("missing_evidence");
  return writeDiagnosticBundle({ selection: evidence.selection, out: options.out, expires_at: options.expires_at, external: options.external }, evidence, fixture);
}
