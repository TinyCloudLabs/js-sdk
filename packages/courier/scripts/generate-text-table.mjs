// Generation only: runtime decisions never consult the host's Unicode property tables.
// Download UnicodeData.txt and DerivedCoreProperties.txt from the pinned Unicode UCD below.
// Run: node scripts/generate-text-table.mjs --ucd-dir <directory>; build; then --vectors.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const unicodeVersion = '15.0.0'; // Unicode in the oldest supported Node 20.0.0.
const sources = {
  'UnicodeData.txt': '806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73',
  'DerivedCoreProperties.txt': 'd367290bc0867e6b484c68370530bdd1a08b6b32404601b8c7accaf83e05628d',
};
const provenance = { unicodeVersion, source: `https://www.unicode.org/Public/${unicodeVersion}/ucd/`, sha256: sources };
if (process.argv.includes('--vectors')) {
  const { textVerdict } = await import('../dist/text.js');
  const ranges = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const sample = `a${String.fromCodePoint(cp)}a`;
    const mask = ['summary', 'multiline', 'target'].reduce((n, field, i) => n | (textVerdict(sample, field).allowed ? 1 << i : 0), 0);
    const last = ranges.at(-1);
    if (last && last[2] === mask) last[1] = cp;
    else ranges.push([cp, cp, mask]);
  }
  const samples = [];
  for (const value of ['Café', 'Cafe\u0301', 'a\u0301', 'a\u0308\u0301', '中文 العربية १२३', 'a\nnext', 'Sam\u2019s PR', "Sam's PR", 'a\u02ba', '\u2126', 'a\u{1c89}a', 'a\u2800a', 'a\u3164a', 'a\u{16fe4}a', 'a\ufe0fa', '', ' a ', 'x'.repeat(201), 'x'.repeat(2001)]) {
    for (const field of ['summary', 'multiline', 'target']) samples.push({ field, value, ...textVerdict(value, field) });
  }
  fs.writeFileSync(path.join(root, 'test/vectors/text-verdicts.json'), JSON.stringify({
    v: 1, ...provenance,
    contract: 'Ranges partition all 1,114,112 code points, inclusive endpoints; mask bits summary=1, multiline=2, target=4. Verdict is textVerdict("a" + codePoint + "a", field), including NFC. Space eligibility is internal; full strings also have type, length and trim rules. Samples include full-string reason codes. Non-ASCII categories Lu|Ll|Lt|Lo|Nd only, minus Default_Ignorable; unassigned in Unicode 15.0.0 refused.',
    summaryPunctuation: ".,:;-_/#()?!'", multilinePunctuation: 'all printable ASCII punctuation',
    ranges, samples,
  }, null, 1) + '\n');
} else {
  const dir = process.argv[process.argv.indexOf('--ucd-dir') + 1];
  if (!process.argv.includes('--ucd-dir') || !dir) throw new Error('--ucd-dir is required (see pinned URLs and hashes in this script)');
  const read = (file) => {
    const data = fs.readFileSync(path.join(dir, file));
    if (createHash('sha256').update(data).digest('hex') !== sources[file]) throw new Error(`UCD hash mismatch: ${file}`);
    return data.toString('utf8');
  };
  const allowed = new Uint8Array(0x110000);
  let first;
  for (const line of read('UnicodeData.txt').trim().split('\n')) {
    const [hex, name, category] = line.split(';');
    const cp = parseInt(hex, 16);
    if (name.endsWith(', First>')) { first = cp; continue; }
    const start = name.endsWith(', Last>') ? first : cp;
    if (['Lu', 'Ll', 'Lt', 'Lo', 'Nd'].includes(category)) allowed.fill(1, start, cp + 1);
    first = undefined;
  }
  for (const line of read('DerivedCoreProperties.txt').split('\n')) {
    const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*Default_Ignorable_Code_Point\b/.exec(line);
    if (match) allowed.fill(0, parseInt(match[1], 16), parseInt(match[2] ?? match[1], 16) + 1);
  }
  const ranges = [];
  for (let cp = 0; cp < allowed.length; cp++) {
    if (!allowed[cp]) continue;
    const last = ranges.at(-1);
    if (last && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  fs.writeFileSync(path.join(root, 'src/text-ranges.ts'), `// Generated by scripts/generate-text-table.mjs; do not hand edit.\n// Unicode ${unicodeVersion}, pinned to the oldest supported Node 20.0.0.\n// Lu|Ll|Lt|Lo|Nd minus Default_Ignorable_Code_Point; unknown/newer characters refused.\n// Source and SHA-256 hashes: test/vectors/text-verdicts.json.\nexport const TEXT_UNICODE_VERSION = '${unicodeVersion}';\nexport const TEXT_ALLOWED_RANGES: readonly (readonly [number, number])[] = Object.freeze([\n${ranges.map(r => `  Object.freeze([0x${r[0].toString(16)}, 0x${r[1].toString(16)}] as const),`).join('\n')}\n]);\n`);
}
